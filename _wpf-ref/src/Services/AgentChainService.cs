namespace FenPeiXiangMuZu.Services;

/// <summary>
/// Agent 连锁支撑服务：占位符统一替换 + 各动作内置默认指令模板。
/// 占位符在编辑器中以按钮快速插入，发送前由 <see cref="ReplacePlaceholders"/> 替换为实际值。
/// </summary>
public static class AgentChainService
{
    // ---- 工具自身路径信息（占位符取值源；惰性缓存一次） ----

    private static readonly Lazy<string> _toolExePath = new(() =>
    {
        try { return Environment.ProcessPath ?? AppContext.BaseDirectory; }
        catch { return AppContext.BaseDirectory; }
    });

    /// <summary>工具 exe 完整路径。</summary>
    public static string ToolExePath => _toolExePath.Value;

    /// <summary>工具 exe 文件名（含扩展名）。</summary>
    public static string ToolExeName => Path.GetFileName(ToolExePath);

    /// <summary>工具 exe 所在目录。</summary>
    public static string ToolRootDir => Path.GetDirectoryName(ToolExePath)?.TrimEnd('\\') ?? "";

    /// <summary>
    /// 统一占位符替换（大小写敏感、未识别的 {…} 原样保留）：
    /// {项目名称}/{文件夹名}=对象显示名；{项目路径}/{路径}=完整路径；
    /// {工具路径}=exe 完整路径；{工具文件名}=exe 文件名；{工具根目录}=exe 目录。
    /// </summary>
    public static string ReplacePlaceholders(string template, string displayName, string fullPath)
    {
        if (string.IsNullOrEmpty(template)) return template ?? "";
        return template
            .Replace("{项目名称}", displayName)
            .Replace("{文件夹名}", displayName)
            .Replace("{项目路径}", fullPath)
            .Replace("{路径}", fullPath)
            .Replace("{工具路径}", ToolExePath)
            .Replace("{工具文件名}", ToolExeName)
            .Replace("{工具根目录}", ToolRootDir);
    }

