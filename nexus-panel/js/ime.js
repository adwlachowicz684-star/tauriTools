/**
 * 输入法（IME）组合期的按键：这一下归输入法，不归界面。
 * ============================================================
 * 中文 / 日文输入时，**回车是「把候选词上屏」，Esc 是「取消这次组合」**——
 * 都不是界面上那个「确定 / 取消」。组合中浏览器照样派发 keydown，
 * 不拦的后果按严重度排：
 *
 *   1. **新建子目录**（folder-picker 的「新建」）：拼音打完按回车选词
 *      → 磁盘上真多出一个名叫拼音的目录，而用户以为自己在选词，
 *      **全程没有任何报错**。
 *   2. **改名**（画布页签 / 库分组 / 收藏昵称）：名字被写成拼音串并落盘。
 *   3. **授权目录 / 收藏路径**：中文路径（D:\我的项目）打到一半按回车
 *      → 加进去的是拼音路径。它**不报错**：授权范围静默多了一个
 *      不存在的目录，等到真去读写才撞「路径越权」，而那时没人会
 *      想起是这次输入造成的（错在 A、炸在 B）。
 *   4. **Esc**：组合期按 Esc 只是取消候选词，界面却把它当成
 *      「取消整个操作」——打了一半的内容连带输入框一起没了。
 *
 * **只在组合中那一帧放行**：拦下来之后输入法照常上屏，用户再按一次回车
 * （此时已不在组合中）才真的提交。所以这不是"禁用回车键"，
 * 是"这一下回车归输入法"。
 *
 * 两条判据都留着：`isComposing` 是标准属性；`keyCode === 229` 是那些
 * 不给 isComposing 的环境**唯一**的线索（229 即"这个键被 IME 吃掉了"
 * 的约定值）。只认一条会在某个浏览器 / 某个输入法上漏。
 *
 * 【调用方式】
 *   · 原生事件（`addEventListener` / hyperscript 的 `onkeydown:`）→ `isComposing(e)`
 *   · React 合成事件 → `isComposing(e.nativeEvent)`
 *     合成事件**不转发** isComposing，传它会拿到 false ——
 *     也就是守卫静默失效、回到不拦的老样子。
 *
 * 【本项目里同判据的另外几份，为什么没合并成一份】
 *   · `js/dialog.js`、`plugins/mindmap/*` 写作内联 `e.isComposing || e.keyCode === 229`，
 *     它们的测试按**源码形态**钉住（mindmap-test 有 8 条），改成调这里
 *     要同时改三个测试文件，属于另一次改动；
 *   · `plugins/project-group/utils/ime.ts` 是 TS 版 —— 该插件的测试加载器
 *     只解析 `./x` / `../x` 形式的 .ts 引用，跨插件引不到这里的 js。
 *   `ime-guard-cross-plugin-test.mjs` 钉住这几份**行为一致**（同一张输入表
 *   必须给出同样的结果），所以它们只是写法不同，不是各改各的。
 */
export function isComposing(n) {
  if (!n) return false;
  return n.isComposing === true || n.keyCode === 229;
}
