/**
 * 上边栏 + 左中右三栏的布局状态（纯逻辑层）。
 *
 * 右栏是「设置在上、日志在下」的**上下分栏**（可拖分隔条调高度），
 * 不是可切标签 —— 跑流程时盯着日志还得能改参数，
 * 切成标签就得来回切，那两件事恰恰经常同时发生。
 *
 * ================= 为什么抽出来 =================
 *
 * 这些是**界面状态**，但它们有必须守住的规则：
 *
 *   · 切到任务视图时左栏要换成「进行中 / 已完成」——
 *     两个视图共用同一条栏、同一套底板，不跟着换就会留一条死栏，
 *     而"点了没反应"是最难自查的一类问题
 *   · 存进 localStorage 的值可能是任意形状（老版本写的、手改的），
 *     不归一就会渲染出一个谁都不认识的标签，**点了没反应**
 *
 * 规则能被测，所以放 engine 而不是散在组件里各判一次 ——
 * 各判一次迟早分叉（这个项目的老问题）。
 */

/**
 * 左边栏的三个标签。
 *
 * 节点库与模块库**分开**，不再把模块库嵌在节点库里用二级 tab 切：
 *   · 顶层切一次就到，比"先切节点库、再在里面切模块库"少一层
 *   · 更要紧的是，两处都能切同一件事会造成割裂 ——
 *     在一处切了，另一处的状态不动，看起来像没生效
 */
export type LeftTab = 'node' | 'module' | 'canvas';


/**
 * 主视图：只剩「流程 / 任务」两个。
 *
 * 历史不再是一个顶层入口 —— 它与任务窗口的区别只是"跑完没跑完"，
 * 却占了一个和流程平级的位置，于是同一件事要分两处找。
 */
export type MainView = 'flow' | 'tasks';

export const LEFT_TABS: LeftTab[] = ['node', 'module', 'canvas'];

export const LEFT_TAB_LABEL: Record<LeftTab, string> = {
  node: '节点库',
  module: '模块库',
  canvas: '画布',
};

/* ------------------------------------------------------------------ */
/* 任务视图的两个子标签                                                 */
/* ------------------------------------------------------------------ */

/**
 * 任务视图左栏的两个标签。
 *
 * 「进行中」就是原来的任务窗口，「已完成」就是原来的历史窗口 ——
 * 合并成一个视图下并列的两个标签，与流程视图的
 * 节点库 / 模块库 / 画布库 **同一套切法**：
 *
 *   · 顶层只留「流程 / 任务」两个，不再有三个平级入口
 *   · 已完成任务与正在跑的任务本质是同一类东西的不同状态，
 *     分成两个窗口时，找一条刚跑完的记录要先想"它算任务还是算历史"
 */
export type TaskTab = 'running' | 'done';

export const TASK_TABS: TaskTab[] = ['running', 'done'];

export const TASK_TAB_LABEL: Record<TaskTab, string> = {
  running: '进行中',
  done: '已完成',
};

/**
 * 把任意值归一成合法的任务子标签。
 *
 * 默认退回 **running**：任务视图的主要用途是盯正在跑的，
 * 而"打开却发现停在看不懂的那一页"比"没停在我上次看的地方"更糟。
 */
export function normalizeTaskTab(v: unknown): TaskTab {
  /*
   * 'history' 是合并前那个顶层「历史」入口留下的值。
   * 认它并落到 done —— 上次在看历史的人，这次应该停在"已完成"，
   * 而不是回到"进行中"再自己找一遍。
   */
  return v === 'done' || v === 'history' ? 'done' : 'running';
}

/* ------------------------------------------------------------------ */
/* 右栏日志高度                                                        */
/* ------------------------------------------------------------------ */

/** 日志区高度的可调范围（px） */
export const LOG_H_MIN = 80;
export const LOG_H_MAX = 600;
export const LOG_H_DEFAULT = 200;

/**
 * 把任意值归一成合法日志高度。
 *
 * 存进 localStorage 的值可能是任意形状（老版本写的、手改的），
 * 直接拿来当 style.height 会渲染出一个 NaNpx —— 面板凭空消失。
 */
export function normalizeLogHeight(v: unknown): number {
  /*
   * "没值"必须先单独挡掉，不能交给下面的夹取 ——
   * Number(null) 是 0，会被夹成 LOG_H_MIN，于是日志区缩成一条缝。
   * 那是**看起来像设过、其实是脏值**的状态，比直接给默认值更难发现。
   */
  if (v == null || v === '') return LOG_H_DEFAULT;
  const n = typeof v === 'number' ? v : Number(v);
  if (!Number.isFinite(n)) return LOG_H_DEFAULT;
  return Math.min(LOG_H_MAX, Math.max(LOG_H_MIN, Math.round(n)));
}

/* ------------------------------------------------------------------ */
/* 归一                                                                */
/* ------------------------------------------------------------------ */

/**
 * 把任意值归一成合法标签。
 *
 * 未知值一律退回默认 —— 存了不认识的值时，最坏结果是显示默认标签，
 * 而不是渲染出一个点不动的空面板。
 */
export function normalizeLeftTab(v: unknown): LeftTab {
  return v === 'module' ? 'module' : v === 'canvas' ? 'canvas' : 'node';
}


/* ------------------------------------------------------------------ */
/* 可见性                                                              */
/* ------------------------------------------------------------------ */

/**
 * 画布置于左边栏时，是否在画布标签上也能编辑。
 *
 * 只有流程视图能编辑 —— 与画布区本身的可见性保持一致，
 * 否则会出现"左边能改、中间看不见"的割裂状态。
 */
export function leftPaneEditable(view: MainView): boolean {
  return view === 'flow';
}

/**
 * 当前视图下左栏该显示哪一组标签。
 *
 * 两个视图**都有**左栏内容（流程是三个库，任务是进行中/已完成），
 * 所以不再有"隐藏左栏"这回事 —— 以前任务视图下左栏被整条隐去，
 * 于是同样宽的一条栏在不同视图下时有时无，切过去整个布局跳一下。
 */
export function leftTabsFor(view: MainView): string[] {
  return view === 'tasks' ? (TASK_TABS as string[]) : (LEFT_TABS as string[]);
}
