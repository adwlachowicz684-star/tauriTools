/**
 * 插件商店面板 —— Vite 构建模式下的**同页（module）入口**
 * ============================================================
 * 本文件是薄薄一层 re-export，真身在 ./index.js。
 *
 * 为什么需要它（而不是让 registry 直接指 index.js）
 * ------------------------------------------------------------
 * js/plugin-entries.js 的 import.meta.glob 只匹配
 * `plugins/<id>/module.{js,mjs,ts,tsx}` —— 换成 index.js 就不会被
 * 构建期收录，产物里没有对应 chunk，表现为**运行时 404**
 * （这正是当初"Vite 模式下只能 iframe"的根因）。
 *
 * 真身为什么不动
 * ------------------------------------------------------------
 * index.js 是无构建模式的同页入口，且被 plugin-panel-actions-test /
 * custom-plugin-save-test 直接读源码守着。改名会让它们全部指空。
 * 加一层比改一遍更省，也更不容易漏。
 *
 * 为什么两种模式都能用这一个入口
 * ------------------------------------------------------------
 * index.js 是纯 JS、无 React 依赖（与工具栏那几个 module.js 同款），
 * 所以无构建（源码直出动态 import）与 Vite（glob 收录打 chunk）
 * 两条路指向同一份文件即可，不需要各写一套。
 */
