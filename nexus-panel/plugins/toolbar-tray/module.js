/**
 * 工具栏插件：隐藏到托盘
 *
 * 原 ⇲ 按钮。动作与 Ctrl+~ 是同一个（host.win('hide')）。
 *
 * 与 ✕ 的关系
 * ------------------------------------------------------------
 * ✕ 的行为由设置决定（隐藏 / 真正退出），这个按钮**恒定是隐藏**。
 * 两个按钮都可能藏窗口，区别是 ✕ 可能是退出 ——
 * 所以 ✕ 留在最右、不进插件口，避免"点哪个才会退出"变得不确定。
 *
 * 藏完给一句提示，说明怎么回来：窗口消失了却不说怎么唤回，
 * 用户第一反应往往是"程序崩了"。
 */
export default {
  id: 'toolbar-tray',
  label: '⇲',
  tip: '隐藏到托盘（点托盘图标唤回）',
  order: 30,
  async onClick(api) {
    await api.win('hide');
    api.toast('已隐藏到托盘 · 点击托盘图标可唤回', 'info');
  },
};
